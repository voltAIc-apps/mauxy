"""
mauxy mailer -- the ONE mail path of mauxy (DOI links, self-check result, operator notifications,
later the Selbst-Check report as PDF / rendered images). SMTP via mailcow mail.mc1.simplify-erp.de.

Every mail goes through send(): validate -> build MIME -> policy -> persist in `mail_outbox`
(idempotent per Message-ID) -> deliver with retry / backoff -> MIME blob dropped once sent.
send() is only ever awaited from background jobs (jobs.py / lead_sync outbox), never on the
request path; queued rows survive a restart (resume()).

MAIL_MODE:
  smtp     (default) send via SMTP_* below
  console  dev only: print the mail INCLUDING the body to stdout -- never in prod
  memory   append to OUTBOX (tests)

SMTP (12-factor, env only):
  SMTP_HOST, SMTP_PORT (default 587 starttls / 465 ssl), SMTP_SECURITY starttls (default) | ssl,
  SMTP_USER, SMTP_PASSWORD, SMTP_FROM ("Name <addr>"), SMTP_REPLY_TO, SMTP_TIMEOUT (s, default 30),
  SMTP_CA_FILE (optional extra trust anchor: local mock servers / tests only).
  TLS is mandatory: ssl.create_default_context() (certificate + hostname verification, TLS >= 1.2).
  starttls: the server MUST offer STARTTLS, else the mail is refused (fail closed, never plaintext);
  AUTH only after TLS. There is no "none" security mode.

Policy (no open relay -- there is no endpoint that takes a recipient + content from outside):
  audience doi        the DOI link mail itself (address not confirmed yet): no attachments
  audience confirmed  the address passed the double opt-in (caller's responsibility)
  audience internal   recipient must be configured (MAIL_INTERNAL_RECIPIENTS, SELFCHECK_NOTIFY_TO,
                      LEAD_NOTIFY_TO)
  one recipient per message, no Cc/Bcc; addresses validated; CR/LF stripped from header text.
  attachments: bytes generated by mauxy only (Attachment objects; never paths, URLs or uploads),
  MIME allow-list MAIL_ATTACHMENT_TYPES (pdf, png, jpeg, webp), content checked against the type
  (magic bytes), total size <= MAIL_MAX_BYTES (default 10 MiB).
  per-recipient limit MAIL_RECIPIENT_HOURLY_LIMIT (default 10 / h; internal recipients exempt).

Logs: message-id, recipient hash, state, error class / SMTP code. Never bodies, attachments,
subjects or credentials.
"""
from __future__ import annotations

import asyncio
import email
import email.policy
import email.utils
import hashlib
import logging
import os
import re
import smtplib
import socket
import ssl
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from email.message import EmailMessage
from typing import Iterable, Literal, Optional

import aiosqlite
from email_validator import EmailNotValidError, validate_email

logger = logging.getLogger("mauxy.mailer")

Audience = Literal["doi", "confirmed", "internal"]
DEFAULT_TYPES = ("application/pdf", "image/png", "image/jpeg", "image/webp")
# content sniffing per allowed type (the declared type must match the bytes)
MAGIC = {
    "application/pdf": lambda b: b.startswith(b"%PDF-"),
    "image/png": lambda b: b.startswith(b"\x89PNG\r\n\x1a\n"),
    "image/jpeg": lambda b: b.startswith(b"\xff\xd8\xff"),
    "image/webp": lambda b: len(b) > 12 and b[:4] == b"RIFF" and b[8:12] == b"WEBP",
}
_CID = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
_CTRL = re.compile(r"[\x00-\x1f\x7f]")

# Captured mails in MAIL_MODE=memory (tests only)
OUTBOX: list[dict] = []

_db: Optional[aiosqlite.Connection] = None


class MailRejected(ValueError):
    """Input / policy violation: the mail is never sent (no retry)."""


class MailTransient(RuntimeError):
    """Delivery may succeed later (network, 4xx)."""


class MailPermanent(RuntimeError):
    """Delivery will not succeed by retrying (5xx, auth, TLS refused / not offered)."""


@dataclass(frozen=True)
class Attachment:
    """A file generated by mauxy (report PDF, rendered image). inline_cid: shown inside the HTML
    part via <img src="cid:...">, images only."""
    filename: str
    content: bytes
    mime_type: str
    inline_cid: Optional[str] = None


# ---------------------------------------------------------------------------- settings (read at call time)


def _env(name: str, default: str = "") -> str:
    return os.environ.get(name, default).strip()


def settings() -> dict:
    security = _env("SMTP_SECURITY", "starttls").lower()
    return {
        "mode": _env("MAIL_MODE", "smtp").lower(),
        "host": _env("SMTP_HOST"),
        "security": security,
        "port": int(_env("SMTP_PORT") or (465 if security == "ssl" else 587)),
        "user": _env("SMTP_USER"),
        "password": os.environ.get("SMTP_PASSWORD", ""),
        "from": _env("SMTP_FROM"),
        "reply_to": _env("SMTP_REPLY_TO"),
        "timeout": float(_env("SMTP_TIMEOUT") or 30),
        "ca_file": _env("SMTP_CA_FILE") or None,
        "max_bytes": int(_env("MAIL_MAX_BYTES") or 10 * 1024 * 1024),
        "types": tuple(t.strip() for t in (_env("MAIL_ATTACHMENT_TYPES") or ",".join(DEFAULT_TYPES)).split(",")
                       if t.strip() in MAGIC),
        "hourly_limit": int(_env("MAIL_RECIPIENT_HOURLY_LIMIT") or 10),
        "max_attempts": max(1, int(_env("MAIL_MAX_ATTEMPTS") or 4)),
        "backoff": float(_env("MAIL_BACKOFF_SECONDS") or 30),
        "retention_days": int(_env("MAIL_RETENTION_DAYS") or 7),
    }


def configured() -> bool:
    """True when a mail can actually leave (or is captured on purpose)."""
    s = settings()
    if s["mode"] in ("console", "memory"):
        return True
    return s["mode"] == "smtp" and bool(s["host"] and s["from"]) and s["security"] in ("starttls", "ssl")


def internal_recipients() -> set[str]:
    raw = ",".join(os.environ.get(k, "") for k in ("MAIL_INTERNAL_RECIPIENTS", "SELFCHECK_NOTIFY_TO", "LEAD_NOTIFY_TO"))
    out = set()
    for a in raw.split(","):
        try:
            out.add(normalize_address(a))
        except MailRejected:
            pass
    return out


# ---------------------------------------------------------------------------- validation helpers


def normalize_address(addr: str) -> str:
    """One plain address (no display name), ASCII for the SMTP envelope, lower-cased domain."""
    if not isinstance(addr, str) or not addr.strip() or _CTRL.search(addr) or len(addr) > 254:
        raise MailRejected("invalid address")
    try:
        # test_environment: also accepts the reserved .test TLD (tests, local runs); no DNS lookups
        v = validate_email(addr.strip(), check_deliverability=False, test_environment=True)
    except EmailNotValidError:
        raise MailRejected("invalid address") from None
    ascii_addr = getattr(v, "ascii_email", None)
    if not ascii_addr:  # non-ASCII local part would need SMTPUTF8
        raise MailRejected("non-ascii address")
    return ascii_addr.lower()


def recipient_hash(addr: str) -> str:
    return hashlib.sha256(addr.lower().encode()).hexdigest()


def clean_header(text: str, limit: int = 200) -> str:
    """Header text without CR/LF / control characters (header injection), length-limited."""
    return re.sub(r"\s+", " ", _CTRL.sub(" ", text or "")).strip()[:limit]


def clean_filename(name: str) -> str:
    base = re.split(r"[\\/]", name or "")[-1]
    base = _CTRL.sub("", base).strip().lstrip(".")
    return base[:120] or "anhang"


def _from_parts(s: dict) -> tuple[str, str]:
    """(header value, envelope address) of SMTP_FROM."""
    display, addr = email.utils.parseaddr(s["from"])
    envelope = normalize_address(addr)
    return (email.utils.formataddr((clean_header(display, 80), envelope)) if display else envelope), envelope


def message_id(domain: str, key: Optional[str]) -> str:
    """<hash@our-domain>; deterministic for an idempotency key, random otherwise."""
    if key:
        return f"<{hashlib.sha256(key.encode()).hexdigest()[:32]}.mauxy@{domain}>"
    return email.utils.make_msgid(idstring="mauxy", domain=domain)


# ---------------------------------------------------------------------------- build


def build(to: str, subject: str, body: str, *, html: Optional[str] = None,
          attachments: Iterable[Attachment] = (), reply_to: Optional[str] = None,
          audience: Audience = "doi", key: Optional[str] = None,
          list_unsubscribe: Optional[str] = None) -> tuple[EmailMessage, str, str]:
    """Validated message -> (EmailMessage, envelope from, envelope to). Raises MailRejected."""
    s = settings()
    rcpt = normalize_address(to)
    if audience not in ("doi", "confirmed", "internal"):
        raise MailRejected("unknown audience")
    if audience == "internal" and rcpt not in internal_recipients():
        raise MailRejected("internal audience but recipient not configured")
    atts = list(attachments)
    if atts and audience == "doi":
        raise MailRejected("attachments only to confirmed or internal recipients")
    total = len(body.encode()) + len((html or "").encode())
    for a in atts:
        if not isinstance(a, Attachment) or not isinstance(a.content, (bytes, bytearray)):
            raise MailRejected("attachment must be generated bytes")
        if a.mime_type not in s["types"]:
            raise MailRejected("attachment type not allowed")
        if not MAGIC[a.mime_type](bytes(a.content)):
            raise MailRejected("attachment content does not match its type")
        if a.inline_cid is not None:
            if not a.mime_type.startswith("image/") or not html or not _CID.match(a.inline_cid):
                raise MailRejected("inline needs an image, an HTML part and a plain cid")
        total += len(a.content)
    if total > s["max_bytes"]:
        raise MailRejected("mail too large")

    from_header, envelope_from = _from_parts(s)
    domain = envelope_from.rsplit("@", 1)[1]
    msg = EmailMessage(policy=email.policy.SMTP)
    msg["From"] = from_header
    msg["To"] = rcpt
    msg["Subject"] = clean_header(subject)
    msg["Date"] = email.utils.formatdate(localtime=False)
    msg["Message-ID"] = message_id(domain, key)
    msg["Auto-Submitted"] = "auto-generated"
    rt = None
    for candidate in (reply_to, s["reply_to"]):
        if candidate:
            try:
                rt = normalize_address(candidate)
                break
            except MailRejected:
                logger.warning("MAIL_REPLY_TO_DROPPED (invalid)")
    if rt:
        msg["Reply-To"] = rt
    if list_unsubscribe:  # list mails only (RFC 2369 / 8058)
        lu = clean_header(list_unsubscribe, 500)
        if not lu.startswith(("https://", "mailto:")):
            raise MailRejected("List-Unsubscribe must be https: or mailto:")
        msg["List-Unsubscribe"] = f"<{lu}>"
        if lu.startswith("https://"):
            msg["List-Unsubscribe-Post"] = "List-Unsubscribe=One-Click"

    msg.set_content(body, charset="utf-8")
    if html:
        msg.add_alternative(html, subtype="html", charset="utf-8")
        html_part = msg.get_payload()[-1]
        for a in atts:
            if a.inline_cid:
                maintype, subtype = a.mime_type.split("/")
                html_part.add_related(bytes(a.content), maintype=maintype, subtype=subtype,
                                      cid=f"<{a.inline_cid}>", filename=clean_filename(a.filename),
                                      disposition="inline")
    for a in atts:
        if not a.inline_cid:
            maintype, subtype = a.mime_type.split("/")
            msg.add_attachment(bytes(a.content), maintype=maintype, subtype=subtype,
                               filename=clean_filename(a.filename))
    return msg, envelope_from, rcpt


# ---------------------------------------------------------------------------- SMTP transport


def _tls_context(s: dict) -> ssl.SSLContext:
    ctx = ssl.create_default_context(cafile=s["ca_file"])  # CERT_REQUIRED + check_hostname
    ctx.minimum_version = ssl.TLSVersion.TLSv1_2
    return ctx


def _classify(exc: BaseException) -> Exception:
    if isinstance(exc, (MailTransient, MailPermanent)):
        return exc
    if isinstance(exc, smtplib.SMTPRecipientsRefused):
        codes = [c for c, _ in exc.recipients.values()]
        return MailTransient(f"rcpt {codes}") if codes and all(400 <= c < 500 for c in codes) else MailPermanent(f"rcpt {codes}")
    if isinstance(exc, smtplib.SMTPResponseException):  # incl. auth, sender refused, data error
        return (MailTransient if 400 <= exc.smtp_code < 500 else MailPermanent)(f"smtp {exc.smtp_code}")
    if isinstance(exc, ssl.SSLError):  # certificate / hostname / handshake: possible MITM, never downgrade
        return MailPermanent(f"tls {exc.__class__.__name__}")
    if isinstance(exc, smtplib.SMTPNotSupportedError):  # e.g. AUTH not offered
        return MailPermanent("smtp extension not supported")
    if isinstance(exc, (smtplib.SMTPServerDisconnected, smtplib.SMTPConnectError, OSError, socket.timeout)):
        return MailTransient(exc.__class__.__name__)
    return MailPermanent(exc.__class__.__name__)


def _deliver_smtp(mime: bytes, envelope_from: str, rcpt: str) -> None:
    """Blocking SMTP delivery (run in a thread). TLS before anything else; fail closed."""
    s = settings()
    if s["security"] not in ("starttls", "ssl"):
        raise MailPermanent("SMTP_SECURITY must be starttls or ssl")
    if not s["host"]:
        raise MailPermanent("SMTP_HOST not set")
    ctx = _tls_context(s)
    try:
        if s["security"] == "ssl":
            srv = smtplib.SMTP_SSL(s["host"], s["port"], context=ctx, timeout=s["timeout"])
        else:
            srv = smtplib.SMTP(s["host"], s["port"], timeout=s["timeout"])
        try:
            srv.ehlo()
            if s["security"] == "starttls":
                if not srv.has_extn("starttls"):
                    raise MailPermanent("starttls not offered")  # no plaintext fallback
                srv.starttls(context=ctx)  # verifies certificate + hostname (server_hostname = host)
                srv.ehlo()
            if s["user"]:
                srv.login(s["user"], s["password"])
            srv.sendmail(envelope_from, [rcpt], mime)
        finally:
            try:
                srv.quit()
            except Exception:
                srv.close()
    except Exception as exc:  # classified, re-raised without the server's message text
        raise _classify(exc) from None


# ---------------------------------------------------------------------------- outbox


def bind(db: Optional[aiosqlite.Connection]) -> None:
    """lifespan: the DB that holds mail_outbox (db-patches/0005). None = no persistence."""
    global _db
    _db = db


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _iso(dt: datetime) -> str:
    return dt.isoformat(timespec="seconds")


async def _row(mid: str) -> Optional[dict]:
    if _db is None:
        return None
    async with _db.execute("SELECT * FROM mail_outbox WHERE message_id = ?", (mid,)) as cur:
        r = await cur.fetchone()
    return dict(r) if r else None


async def _update(mid: str, **vals) -> None:
    if _db is None:
        return
    cols = ", ".join(f"{k} = ?" for k in vals)  # fixed column names from this module
    await _db.execute(f"UPDATE mail_outbox SET {cols} WHERE message_id = ?", (*vals.values(), mid))
    await _db.commit()


async def _recent_count(rh: str) -> int:
    if _db is None:
        return 0
    since = _iso(_now() - timedelta(hours=1))
    async with _db.execute(
            "SELECT COUNT(*) FROM mail_outbox WHERE recipient_hash = ? AND audience != 'internal' "
            "AND state IN ('queued', 'sent') AND created_at >= ?", (rh, since)) as cur:
        (n,) = await cur.fetchone()
    return n


def _log(event: str, mid: str, rh: str, **extra) -> None:
    tail = " ".join(f"{k}={v}" for k, v in extra.items())
    logger.info("%s message_id=%s rcpt=%s %s", event, mid, rh[:12], tail)


async def _transport(mime: bytes, envelope_from: str, rcpt: str, meta: dict) -> None:
    mode = settings()["mode"]
    if mode == "memory":
        OUTBOX.append(meta)
    elif mode == "console":
        print(f"MAIL_CONSOLE (dev, not sent) to={rcpt}\n{mime.decode('utf-8', 'replace')}\n---", flush=True)
    elif mode == "smtp":
        await asyncio.to_thread(_deliver_smtp, mime, envelope_from, rcpt)
    else:
        raise MailPermanent(f"unknown MAIL_MODE {mode}")


async def _attempts(mid: str, rh: str, mime: bytes, envelope_from: str, rcpt: str, meta: dict,
                    done: int) -> bool:
    s = settings()
    for attempt in range(done + 1, s["max_attempts"] + 1):
        try:
            await _transport(mime, envelope_from, rcpt, meta)
        except MailTransient as exc:
            last = str(exc)[:80]
            if attempt >= s["max_attempts"]:
                break
            delay = min(s["backoff"] * 2 ** (attempt - 1), 3600)
            await _update(mid, attempts=attempt, last_error=last, next_attempt_at=_iso(_now() + timedelta(seconds=delay)))
            _log("MAIL_RETRY", mid, rh, attempt=attempt, error=last, delay=delay)
            await asyncio.sleep(delay)
            continue
        except MailPermanent as exc:
            await _update(mid, attempts=attempt, state="failed", last_error=str(exc)[:80], mime=None, done_at=_iso(_now()))
            _log("MAIL_FAILED", mid, rh, attempt=attempt, error=str(exc)[:80])
            return False
        await _update(mid, attempts=attempt, state="sent", last_error=None, mime=None, done_at=_iso(_now()))
        _log("MAIL_SENT", mid, rh, attempt=attempt)
        return True
    await _update(mid, attempts=s["max_attempts"], state="failed", mime=None, done_at=_iso(_now()))
    _log("MAIL_FAILED", mid, rh, attempt=s["max_attempts"], error="retries exhausted")
    return False


async def send(to: str, subject: str, body: str, reply_to: Optional[str] = None, *,
               html: Optional[str] = None, attachments: Iterable[Attachment] = (),
               audience: Audience = "doi", key: Optional[str] = None,
               list_unsubscribe: Optional[str] = None) -> bool:
    """Send one mail (see module doc). Await it from a background job only. True = sent (or sent
    before under the same key), False = refused / failed. Never raises, never logs content."""
    try:
        msg, envelope_from, rcpt = build(to, subject, body, html=html, attachments=attachments,
                                         reply_to=reply_to, audience=audience, key=key,
                                         list_unsubscribe=list_unsubscribe)
    except MailRejected as exc:
        logger.error("MAIL_REFUSED reason=%s", exc)
        return False
    except Exception as exc:  # misconfigured SMTP_FROM etc.
        logger.error("MAIL_REFUSED reason=%s", exc.__class__.__name__)
        return False
    mid, rh = msg["Message-ID"], recipient_hash(rcpt)
    atts = list(attachments)
    meta = {"to": rcpt, "subject": msg["Subject"], "body": body, "reply_to": msg["Reply-To"], "html": html,
            "attachments": [(clean_filename(a.filename), a.mime_type, a.inline_cid) for a in atts],
            "audience": audience, "message_id": mid, "mime": None}
    mime = msg.as_bytes()
    meta["mime"] = mime

    existing = await _row(mid)
    if existing:
        if existing["state"] == "sent":
            _log("MAIL_DUPLICATE_SKIPPED", mid, rh)
            return True
        if existing["state"] == "failed":
            return False
        return await _attempts(mid, rh, mime, envelope_from, rcpt, meta, existing["attempts"])
    if audience != "internal" and await _recent_count(rh) >= settings()["hourly_limit"]:
        _log("MAIL_RATE_LIMITED", mid, rh)
        return False
    if _db is not None:
        await _db.execute(
            "INSERT OR IGNORE INTO mail_outbox (message_id, recipient_hash, audience, mime, created_at) "
            "VALUES (?, ?, ?, ?, ?)", (mid, rh, audience, mime, _iso(_now())))
        await _db.commit()
    return await _attempts(mid, rh, mime, envelope_from, rcpt, meta, 0)


async def resume(spawn) -> int:
    """lifespan: re-deliver mails that were queued when the process stopped. `spawn(coro, name)`."""
    if _db is None:
        return 0
    async with _db.execute("SELECT message_id, recipient_hash, mime, attempts FROM mail_outbox "
                           "WHERE state = 'queued' AND mime IS NOT NULL") as cur:
        rows = [dict(r) for r in await cur.fetchall()]
    for r in rows:
        mime = bytes(r["mime"])
        parsed = email.message_from_bytes(mime, policy=email.policy.SMTP)
        try:
            _, envelope_from = _from_parts(settings())
            rcpt = normalize_address(str(parsed["To"]))
        except MailRejected:
            await _update(r["message_id"], state="failed", mime=None, last_error="resume: invalid", done_at=_iso(_now()))
            continue
        meta = {"to": rcpt, "subject": str(parsed["Subject"]), "body": None, "message_id": r["message_id"],
                "resumed": True, "mime": mime}
        spawn(_attempts(r["message_id"], r["recipient_hash"], mime, envelope_from, rcpt, meta, r["attempts"]),
              name="mail_resume")
    return len(rows)


async def purge(db: aiosqlite.Connection) -> None:
    """Retention: finished rows after MAIL_RETENTION_DAYS; queued rows older than 2 days fail."""
    s = settings()
    now = _now()
    await db.execute("DELETE FROM mail_outbox WHERE state != 'queued' AND COALESCE(done_at, created_at) < ?",
                     (_iso(now - timedelta(days=s["retention_days"])),))
    await db.execute("UPDATE mail_outbox SET state = 'failed', mime = NULL, last_error = 'expired', done_at = ? "
                     "WHERE state = 'queued' AND created_at < ?", (_iso(now), _iso(now - timedelta(days=2))))
    await db.commit()
